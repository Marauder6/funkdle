// npm run data:audit: writes data/audit-report.md (SPEC 6.1). Regenerated whole on every run;
// the simulation section is a placeholder until data:simulate fills it.

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { compare } from "../src/core/compare";
import { DEFAULT_FEEDBACK, GUESS_LIMIT, INCLUDE_CREATION_CLUB } from "../src/core/config";
import { collisionClasses } from "../src/core/fingerprint";
import {
  COMPONENT_NAMES,
  ORIGINS,
  componentTypes,
  weightHundredths,
  type CellState,
  type Feedback,
  type Item,
} from "../src/core/types";
import { crossCheck } from "./lib/crosscheck";
import { SIM_BEGIN, SIM_END } from "./lib/markers";
import { AUDIT_PATH, ITEMS_PATH, loadSnapshot } from "./lib/raw";
import { runBuild } from "./lib/run-build";
import { counts, entropyBits, pct, quantile } from "./lib/stats";

const { dataset, json, report } = runBuild();
const committed = readFileSync(ITEMS_PATH, "utf8");
if (committed !== json) {
  console.error(
    "data/items.json differs from what data:build produces now. Run npm run data:build first.",
  );
  process.exit(1);
}
const itemsSha = createHash("sha256").update(committed, "utf8").digest("hex");

const items = dataset.items;
const pool = items.filter((i) => i.inTargetPool);
const lines: string[] = [];
const out = (...l: string[]) => lines.push(...l);
const lb = (h: number) => `${h / 100} lb`;
const fmt = (n: number, d = 2) => (Number.isInteger(n) ? String(n) : n.toFixed(d));
const describe = (i: Item) =>
  `${i.weight} lb, ${i.value} caps, ${componentTypes(i).join("+")}, total ${i.totalComponents}, ` +
  `${i.uniqueComponents} types, ${i.origin}`;

out(
  "# Funkdle data audit",
  "",
  "Generated by `npm run data:audit` (SPEC 6.1). Do not edit by hand.",
  "",
  `- Source: [${dataset.source.title}](${dataset.source.url}), revision ${dataset.source.revisionId}, retrieved ${dataset.source.retrievedAt}`,
  `- \`data/items.json\` sha256: \`${itemsSha}\``,
  `- Config: weight close within max(${lb(DEFAULT_FEEDBACK.weight.floor)}, ${DEFAULT_FEEDBACK.weight.ratio} x target); ` +
    `value close within max(${DEFAULT_FEEDBACK.value.floor} caps, ${DEFAULT_FEEDBACK.value.ratio} x target); ` +
    `total close within ${DEFAULT_FEEDBACK.totalCloseWithin}; guess limit ${GUESS_LIMIT}; ` +
    `Creation Club ${INCLUDE_CREATION_CLUB ? "included" : "excluded"}`,
  "",
);

// --- Counts
out(
  "## 1. Counts",
  "",
  `Rows parsed: **${report.rowsParsed}**. Items kept (guessable set): **${items.length}**. Target pool: **${pool.length}**.`,
  "",
);
out("| Wiki section | Rows |", "|---|---|");
for (const [s, n] of Object.entries(report.rowsPerSection)) out(`| ${s} | ${n} |`);
out("", "| Origin | Guessable | Target pool |", "|---|---|---|");
for (const o of ORIGINS) {
  out(
    `| ${o} | ${items.filter((i) => i.origin === o).length} | ${pool.filter((i) => i.origin === o).length} |`,
  );
}
out(
  "",
  `### Exclusions (${report.exclusions.length})`,
  "",
  "| Name | Section | Kind | Reason |",
  "|---|---|---|---|",
);
for (const e of report.exclusions) out(`| ${e.name} | ${e.section} | ${e.kind} | ${e.reason} |`);
out("");

// --- Components
out(
  "## 2. Component frequency",
  "",
  "Items in the guessable set that contain each component, any quantity.",
  "",
);
out("| Component | Items | Target-pool items |", "|---|---|---|");
const compRows = COMPONENT_NAMES.map((c) => ({
  c,
  n: items.filter((i) => i.components[c] !== undefined).length,
  p: pool.filter((i) => i.components[c] !== undefined).length,
})).sort((a, b) => b.n - a.n || (a.c < b.c ? -1 : 1));
for (const r of compRows) out(`| ${r.c} | ${r.n} | ${r.p} |`);
out("");

// --- Collisions
const classes = [...collisionClasses(items).values()];
const multi = classes
  .filter((c) => c.length > 1)
  .sort((a, b) => b.length - a.length || (a[0]!.id < b[0]!.id ? -1 : 1));
out("## 3. Collision classes", "");
out(
  `${classes.length} distinct fingerprints across ${items.length} items. ${multi.length} classes have 2 or more members, covering ${items.length - pool.length} items. Target pool (classes of size 1): **${pool.length}**.`,
  "",
);
out("| Class size | Classes | Items |", "|---|---|---|");
for (const [size, n] of [...counts(classes.map((c) => c.length)).entries()].sort(
  (a, b) => a[0] - b[0],
)) {
  out(`| ${size} | ${n} | ${size * n} |`);
}
out("", "| Size | Fingerprint | Members |", "|---|---|---|");
for (const c of multi)
  out(`| ${c.length} | ${describe(c[0]!)} | ${c.map((i) => i.name).join(", ")} |`);
out("");

// --- Merges and conflicts
out(
  "## 4. Names in several sections",
  "",
  `${report.merges.length} names appear in more than one section and were merged into one item with the earliest origin (SPEC 5.3).`,
  "",
);
out("| Name | Kept | Also listed under |", "|---|---|---|");
for (const m of report.merges)
  out(`| ${m.name} | ${m.keptSection} | ${m.otherSections.join(", ")} |`);
out(
  "",
  `### Conflicts (${report.conflicts.length})`,
  "",
  "Rows whose stats differ from the kept record. Resolution: the kept (earliest-origin) record wins; the other row is dropped, form IDs included.",
  "",
);
out("| Name | Kept | Dropped |", "|---|---|---|");
const rs = (r: { section: string; value: number; weight: number; components: string }) =>
  `${r.section}: ${r.value} caps, ${r.weight} lb, ${r.components}`;
for (const c of report.conflicts)
  out(`| ${c.name} | ${rs(c.kept)} | ${c.dropped.map(rs).join("; ")} |`);
out("");

// --- Distributions
out("## 5. Weight and value distributions", "", "Quartiles by linear interpolation.", "");
out(
  "| Column | Set | Min | Q1 | Median | Q3 | Max | Distinct |",
  "|---|---|---|---|---|---|---|---|",
);
for (const [label, get] of [
  ["Weight (lb)", (i: Item) => i.weight],
  ["Value (caps)", (i: Item) => i.value],
] as const) {
  for (const [setName, set] of [
    ["guessable", items],
    ["target pool", pool],
  ] as const) {
    const v = set.map(get).sort((a, b) => a - b);
    out(
      `| ${label} | ${setName} | ${fmt(v[0]!)} | ${fmt(quantile(v, 0.25))} | ${fmt(quantile(v, 0.5))} | ${fmt(quantile(v, 0.75))} | ${fmt(v[v.length - 1]!)} | ${new Set(v).size} |`,
    );
  }
}
out("");

// --- Entropy
out(
  "## 6. Information per column",
  "",
  `Distinct values and Shannon entropy of each column's values over the target pool (${pool.length} items; the maximum possible is log2(${pool.length}) = ${Math.log2(pool.length).toFixed(2)} bits).`,
  "",
);
out("| Column | Distinct values | Entropy (bits) |", "|---|---|---|");
const columns: Array<[string, (i: Item) => string | number]> = [
  ["Weight", (i) => weightHundredths(i)],
  ["Value", (i) => i.value],
  ["Components (type set)", (i) => componentTypes(i).join("+")],
  ["Total components", (i) => i.totalComponents],
  ["Unique types", (i) => i.uniqueComponents],
  ["Origin", (i) => i.origin],
];
for (const [name, get] of columns) {
  const v = pool.map(get);
  out(`| ${name} | ${new Set(v).size} | ${entropyBits(v).toFixed(2)} |`);
}
out("");

// --- Feedback state rates
const pairs = items.length * pool.length;
out(
  "## 7. Feedback state rates",
  "",
  `Share of all ${pairs.toLocaleString("en-US")} (guess, target) pairs, guess from the guessable set and target from the pool, that produce each state under the current config. Same-item pairs are included.`,
  "",
);
out("| Column | match | close | miss |", "|---|---|---|---|");
const tally: Record<string, Record<CellState, number>> = {};
const cols: Array<[string, (f: Feedback) => CellState]> = [
  ["Weight", (f) => f.weight.state],
  ["Value", (f) => f.value.state],
  ["Components", (f) => f.components.state],
  ["Total components", (f) => f.total.state],
  ["Unique types", (f) => f.unique.state],
  ["Origin", (f) => f.origin.state],
];
for (const [name] of cols) tally[name] = { match: 0, close: 0, miss: 0 };
for (const g of items) {
  for (const t of pool) {
    const fb = compare(g, t, DEFAULT_FEEDBACK);
    for (const [name, get] of cols) tally[name]![get(fb)]++;
  }
}
for (const [name] of cols) {
  const t = tally[name]!;
  out(`| ${name} | ${pct(t.match, pairs)} | ${pct(t.close, pairs)} | ${pct(t.miss, pairs)} |`);
}
out("");

// --- Cross-check
out("## 8. Cross-check against the Independent Fallout Wiki", "");
try {
  const { html, meta } = loadSnapshot("fallout-wiki");
  const excludedNames = new Set(
    report.exclusions.filter((e) => e.kind !== "config").map((e) => e.name.toLowerCase()),
  );
  const cc = crossCheck(html, items, excludedNames);
  out(
    `[${meta.title}](${meta.url}), revision ${meta.revisionId}, retrieved ${meta.retrievedAt}. ${cc.rowsParsed} rows parsed. ` +
      "Creation Club items are not compared (that page has no Creation Club table). Names match case-insensitively. Report only: the primary source decides.",
    "",
    `- Rows the cross-check parser could not read: ${cc.unreadable.length}`,
    `- Dataset items with no row on the cross-check page: ${cc.missing.length}`,
    `- Cross-check rows with no dataset item: ${cc.extra.length}`,
    `- Items whose value, weight or components differ: **${cc.differences.length}**`,
    "",
  );
  if (cc.differences.length) {
    out("### Differences", "", "| Item | Nukapedia | fallout.wiki |", "|---|---|---|");
    for (const d of cc.differences) {
      const comps = Object.entries(d.item.components)
        .map(([k, v]) => `${k} x${v}`)
        .join(", ");
      out(
        `| ${d.item.name} | ${d.item.value} caps, ${d.item.weight} lb, ${comps} | ${d.rows.map((r) => `${r.value} caps, ${r.weight} lb, ${r.components}`).join("; ")} |`,
      );
    }
    out("");
  }
  if (cc.unreadable.length) {
    out("### Unreadable cross-check rows", "", "| Section | Name | Problem |", "|---|---|---|");
    for (const u of cc.unreadable) out(`| ${u.section} | ${u.name} | ${u.problem} |`);
    out("");
  }
  if (cc.missing.length)
    out("### Missing from the cross-check page", "", cc.missing.map((i) => i.name).join(", "), "");
  if (cc.extra.length) {
    out(
      "### Only on the cross-check page",
      "",
      "| Section | Name | Value | Weight | Components |",
      "|---|---|---|---|---|",
    );
    for (const r of cc.extra)
      out(`| ${r.section} | ${r.name} | ${r.value} | ${r.weight} | ${r.components} |`);
    out("");
  }
} catch (err) {
  // Degraded, not fatal: the cross-check is advisory. Say so in the report.
  const reason = err instanceof Error ? err.message : String(err);
  out(`**Cross-check not run:** ${reason}`, "");
  console.error(`DEGRADED: cross-check not run: ${reason}`);
}

// --- Simulation placeholder
out(
  "## 9. Solver simulation",
  "",
  SIM_BEGIN,
  "Not yet run for this dataset. Run `npm run data:simulate`.",
  SIM_END,
  "",
);

await writeFile(AUDIT_PATH, lines.join("\n"), "utf8");
console.log(
  `wrote ${AUDIT_PATH}: ${items.length} items, pool ${pool.length}, ${multi.length} collision classes`,
);
